const seedUsage = `usage: kiw seed [flags]
alias: kiw db:seed [flags]

flags:
  --class <name>  seeder class to run (default: DatabaseSeeder)
  --dsn <dsn>     database connection string (overrides APP_DATABASE_DSN and database.dsn)
  --driver <name> database driver: sqlite, postgres, mysql (default: sqlite)
  --dir <path>    seeds directory (default: seeds or database/seeds)`

// RegisterSeed registers flags for the seed / db:seed command.
func RegisterSeed(fs *flag.FlagSet) {
	fs.String("class", "DatabaseSeeder", "seeder class to run (default DatabaseSeeder)")
	fs.String("dsn", "", "database DSN (overrides APP_DATABASE_DSN and database.dsn)")
	fs.String("driver", "", "database/sql driver (overrides APP_DATABASE_DRIVER and database.driver; default sqlite)")
	fs.String("dir", "", "seeds directory (overrides APP_DATABASE_SEEDS and database.seeds; default seeds)")
}

// RunSeed executes project database seeders.
func RunSeed(fs *flag.FlagSet) errs.ExitCode {
	root, err := findRoot()
	if err != nil {
		fmt.Fprintln(os.Stderr, "kiw: "+err.Error())
		return errs.ExitCodeUsage
	}

	db, err := resolveMigrateDatabase(root, fs)
	if err != nil {
		fmt.Fprintln(os.Stderr, "kiw seed: "+err.Error())
		return errs.ExitCodeUsage
	}

	class := flagValue(fs, "class")
	if class == "" {
		class = "DatabaseSeeder"
	}

	dir := flagValue(fs, "dir")
	if dir == "" {
		if db.Seeds != "" && db.Seeds != config.DefaultSeedsDir {
			dir = db.Seeds
		} else {
			// Check database/seeds first, then seeds
			if st, err := os.Stat(filepath.Join(root, "database", "seeds")); err == nil && st.IsDir() {
				dir = filepath.Join("database", "seeds")
			} else if st, err := os.Stat(filepath.Join(root, "seeds")); err == nil && st.IsDir() {
				dir = "seeds"
			} else {
				dir = "seeds"
			}
		}
	}

	absDir := dir
	if !filepath.IsAbs(absDir) {
		absDir = filepath.Join(root, dir)
	}

	st, err := os.Stat(absDir)
	if err != nil || !st.IsDir() {
		fmt.Fprintf(os.Stderr, "kiw seed: seeds directory %s not found. Create one with: kiw make seeder %s\n", dir, class)
		return errs.ExitCodeUsage
	}

	goFiles, _ := filepath.Glob(filepath.Join(absDir, "*.go"))
	if len(goFiles) == 0 {
		fmt.Fprintf(os.Stderr, "kiw seed: no .go seed files found in %s. Create one with: kiw make seeder %s\n", dir, class)
		return errs.ExitCodeUsage
	}

	return runGoSeeds(root, absDir, db, class)
}

func runGoSeeds(root, dir string, db config.DatabaseConfig, class string) errs.ExitCode {
	if db.DSN == "" {
		printMigrateError(os.Stderr, errs.WithHint(errors.New("no database configured"),
			"set database.dsn in krewire.yaml, APP_DATABASE_DSN in the environment or .env, or pass --dsn"))
		return errs.ExitCodeUsage
	}

	mod, err := gomod.Read(filepath.Join(root, "go.mod"))
	if err != nil || mod.Path == "" {
		fmt.Fprintf(os.Stderr, "kiw seed: failed to read go.mod in %s: %v\n", root, err)
		return errs.ExitCodeFailure
	}

	relDir, err := filepath.Rel(root, dir)
	if err != nil {
		relDir = "seeds"
	}
	relDir = filepath.ToSlash(relDir)
	var importPath string
	if relDir == "." {
		importPath = mod.Path
	} else {
		importPath = mod.Path + "/" + relDir
	}

	runnerName := fmt.Sprintf("kiw_seed_runner_%d.go", time.Now().UnixNano())
	runnerPath := filepath.Join(root, runnerName)
	runnerSrc := fmt.Sprintf(`// Code generated by kiw. DO NOT EDIT.
package main

import (
	"context"
	"fmt"
	"os"
	"strings"
	"time"

	_ %q

	"github.com/krewire/krewire/pkg/orm"
	_ "github.com/krewire/krewire/pkg/orm/mysql"
	_ "github.com/krewire/krewire/pkg/orm/postgres"
	"github.com/krewire/krewire/pkg/orm/seeder"
	"github.com/krewire/krewire/pkg/orm/sqlite"
)

func main() {
	driver := os.Getenv("KIW_SEED_DRIVER")
	dsn := os.Getenv("KIW_SEED_DSN")
	class := os.Getenv("KIW_SEED_CLASS")
	if class == "" {
		class = "DatabaseSeeder"
	}

	var conn *orm.DB
	var err error
	switch {
	case driver == "" || driver == "sqlite" || driver == "sqlite3":
		conn, err = sqlite.Open(dsn)
	default:
		conn, err = orm.Open(driver, dsn)
	}
	if err != nil {
		fmt.Fprintf(os.Stderr, "kiw seed: failed to connect to database: %%v\n", err)
		os.Exit(1)
	}
	defer conn.Close()

	ctx := context.Background()
	start := time.Now()

	// Verify target class exists
	if _, ok := seeder.Get(class); !ok {
		registered := seeder.GetRegistered()
		if len(registered) == 0 {
			fmt.Fprintf(os.Stderr, "kiw seed: no seeders registered. Register seeders via seeder.Register(%%q, ...)\n", class)
			os.Exit(1)
		}
		fmt.Fprintf(os.Stderr, "kiw seed: seeder %%q not found. Registered: %%s\n", class, strings.Join(registered, ", "))
		os.Exit(1)
	}

	fmt.Printf("Seeding: %%s\n", class)
	if err := seeder.Run(ctx, conn, class); err != nil {
		fmt.Fprintf(os.Stderr, "kiw seed: %%v\n", err)
		os.Exit(1)
	}
	fmt.Printf("Seeded:  %%s (%%s)\n", class, time.Since(start).Round(time.Millisecond))
	fmt.Println("Database seeding completed successfully.")
}
`, importPath)

	if err := os.WriteFile(runnerPath, []byte(runnerSrc), 0o600); err != nil {
		fmt.Fprintf(os.Stderr, "kiw seed: failed to write runner: %v\n", err)
		return errs.ExitCodeFailure
	}
	defer os.Remove(runnerPath)

	effectiveDSN := db.DSN
	if db.IsSQLite() {
		effectiveDSN = db.SQLitePath(root)
	}

	cmd := exec.Command("go", "run", runnerName)
	cmd.Dir = root
	cmd.Env = append(os.Environ(),
		"KIW_SEED_DRIVER="+db.Driver,
		"KIW_SEED_DSN="+effectiveDSN,
		"KIW_SEED_CLASS="+class,
	)
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	cmd.Stdin = os.Stdin

	if err := cmd.Run(); err != nil {
		return errs.ExitCodeFailure
	}
	return errs.ExitCodeSuccess
}
