// Package clientgen generates a typed Go client from a service contract
// (ref #137). The generated methods are thin wrappers over httpbind.Call, so
// they share the contract's routes, parameter locations, and error semantics
// with the server binding; the generator only adds a named, documented,
// IDE-friendly method per endpoint.
//
// Convention: every endpoint is declared as a package-level apicontract.Def
// variable named exactly like the endpoint (var CreateTodo =
// apicontract.Define[...]("CreateTodo", ...)) in the package DefsImport.
// Compiling the generated code verifies that convention.
package clientgen

import (
	"bytes"
	"fmt"
	"go/format"
	"path"
	"reflect"
	"sort"
	"strconv"
	"strings"
	"text/template"

	"github.com/krewire/krewire/apicontract"
)

// Options configures generation.
type Options struct {
	// Package is the generated package name.
	Package string
	// DefsImport is the import path of the package declaring the Def vars.
	DefsImport string
}

const httpbindImport = "github.com/krewire/krewire/apicontract/httpbind"

type method struct {
	Name, Verb, Path, Summary, Req, Resp string
	Errors                               []string
	Deprecated                           bool
}

var tmpl = template.Must(template.New("client").Parse(`// Code generated by krewire apicontract/clientgen; DO NOT EDIT.
// Contract: {{.Service}} {{.Version}}

package {{.Package}}

import (
	"context"
{{range .Imports}}
	{{.}}{{end}}
)

// ContractVersion is the contract version this client was generated from.
const ContractVersion = {{printf "%q" .Version}}

// Client is the typed client for the {{.Service}} service.
type Client struct {
	HTTP *httpbind.Client
}

// New returns a Client that sends requests through c.
func New(c *httpbind.Client) *Client { return &Client{HTTP: c} }
{{range .Methods}}
// {{.Name}} calls {{.Verb}} {{.Path}}.{{if .Summary}} {{.Summary}}{{end}}
//
// Declared errors: {{range $i, $e := .Errors}}{{if $i}}, {{end}}{{$e}}{{end}}.{{if .Deprecated}}
//
// Deprecated: the contract marks this endpoint deprecated.{{end}}
func (c *Client) {{.Name}}(ctx context.Context, req *{{.Req}}) (*{{.Resp}}, error) {
	return httpbind.Call(ctx, c.HTTP, {{$.Defs}}.{{.Name}}, req)
}
{{end}}`))

// Generate renders gofmt-formatted Go source for svc's client.
func Generate(svc *apicontract.Service, opts Options) ([]byte, error) {
	if opts.Package == "" || opts.DefsImport == "" {
		return nil, fmt.Errorf("clientgen: Package and DefsImport are required")
	}
	doc, err := svc.Compile()
	if err != nil {
		return nil, err
	}
	im := newImports()
	defs := im.alias(opts.DefsImport)
	var methods []method
	for _, ep := range svc.Endpoints() {
		req, err := im.typeExpr(ep.Request)
		if err != nil {
			return nil, fmt.Errorf("clientgen: %s request: %w", ep.Name, err)
		}
		resp, err := im.typeExpr(ep.Response)
		if err != nil {
			return nil, fmt.Errorf("clientgen: %s response: %w", ep.Name, err)
		}
		var errs []string
		for _, e := range doc.Endpoint(ep.Name).Errors {
			errs = append(errs, e.Code+" ("+strconv.Itoa(e.Status)+")")
		}
		methods = append(methods, method{
			Name: ep.Name, Verb: ep.Method, Path: doc.BasePath + ep.Path,
			Summary: ep.Summary, Req: req, Resp: resp, Errors: errs, Deprecated: ep.Deprecated,
		})
	}
	im.alias(httpbindImport)
	var buf bytes.Buffer
	err = tmpl.Execute(&buf, map[string]any{
		"Package": opts.Package, "Service": doc.Service, "Version": doc.Version,
		"Imports": im.lines(), "Methods": methods, "Defs": defs,
	})
	if err != nil {
		return nil, err
	}
	out, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("clientgen: format: %w", err)
	}
	return out, nil
}

type imports struct {
	byPath map[string]string
	used   map[string]bool
}

func newImports() *imports {
	return &imports{byPath: map[string]string{}, used: map[string]bool{"context": true}}
}

func (im *imports) alias(p string) string {
	if a, ok := im.byPath[p]; ok {
		return a
	}
	base := strings.NewReplacer("-", "", ".", "").Replace(path.Base(p))
	a := base
	for i := 2; im.used[a]; i++ {
		a = base + strconv.Itoa(i)
	}
	if p == httpbindImport {
		a = "httpbind" // referenced by name in the template
	}
	im.byPath[p], im.used[a] = a, true
	return a
}

func (im *imports) lines() []string {
	var out []string
	for p, a := range im.byPath {
		if a == path.Base(p) {
			out = append(out, strconv.Quote(p))
		} else {
			out = append(out, a+" "+strconv.Quote(p))
		}
	}
	sort.Slice(out, func(i, j int) bool { return unalias(out[i]) < unalias(out[j]) })
	return out
}

func unalias(line string) string {
	if i := strings.IndexByte(line, '"'); i >= 0 {
		return line[i:]
	}
	return line
}

// typeExpr renders a named type as a qualified Go expression.
func (im *imports) typeExpr(t reflect.Type) (string, error) {
	if t.Name() == "" || t.PkgPath() == "" {
		return "", fmt.Errorf("type %s must be a named type", t)
	}
	if strings.ContainsAny(t.Name(), "[]") {
		return "", fmt.Errorf("generic type %s is not supported; declare a named alias", t)
	}
	return im.alias(t.PkgPath()) + "." + t.Name(), nil
}
